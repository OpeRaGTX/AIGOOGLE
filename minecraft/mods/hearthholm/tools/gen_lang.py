def write(lang, idx):
    data = {k: v[idx] for k, v in T.items()}
    for i, (m, f) in enumerate(zip(M_EN if idx == 0 else M_RU, F_EN if idx == 0 else F_RU)):
        data[f"settler.hearthholm.name.m.{i}"] = m
        data[f"settler.hearthholm.name.f.{i}"] = f
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, lang + ".json"), "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=1, ensure_ascii=False)
        fh.write("\n")

